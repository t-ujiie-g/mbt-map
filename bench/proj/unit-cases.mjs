// Writes proj/projections_test.mbt: proj4js 2.22.0's result at one point of each PROJ string of golden.mjs,
// so `moon test` (and CI) checks every projection. Usage: node proj/unit-cases.mjs, then `moon fmt`.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import proj4 from "proj4";
import { parseProjString } from "../../npm/src/projstring.ts";
import { ROOT } from "../lib/root.mjs";

const golden = await readFile(path.join(ROOT, "bench/proj/golden.mjs"), "utf8");
const strings = [...golden.matchAll(/^  \["([^"]+)", "(\+proj=[^"]+)", \[([^\]]+)\]\],$/gm)].map((m) => [m[1], m[2], m[3].split(",").map(Number)]);
const num = (x) => (Number.isNaN(x) ? "nan" : Number.isInteger(x) ? x.toFixed(1) : String(x));
const cases = strings.map(([name, def, [w, s, e, n]]) => {
  const lonlat = [w + 0.3 * (e - w), s + 0.6 * (n - s)];
  const xy = proj4("EPSG:4326", proj4.Proj(def), lonlat);
  if (!xy.every(Number.isFinite)) throw new Error(`proj4js gives no point for ${name}`);
  return `    (\n      "${name}",\n      [${[...parseProjString(def)].map(num).join(", ")}],\n      (${lonlat.map(num).join(", ")}),\n      (${xy.map(num).join(", ")}),\n    ),`;
});
const text = `// Generated by bench/proj/unit-cases.mjs from proj4js 2.22.0.

///|
/// One point of each PROJ string of bench/proj/golden.mjs: name, definition
/// slots (npm/src/projstring.ts), longitude and latitude, proj4js's x and y.
let projection_cases : Array[(String, Array[Double], (Double, Double), (Double, Double))] = {
  let nan = @double.not_a_number
  [
${cases.join("\n")}
  ]
}

///|
test "every projection matches proj4js on a point, and comes back" {
  let wgs = epsg(4326)
  for c in projection_cases {
    let (name, slots, lonlat, expected) = c
    guard @proj.Definition::decode(slots[:]) is Some(d) &&
      @proj.Crs::new(d) is Some(crs) else {
      fail(name)
    }
    guard @proj.transform(wgs, crs, lonlat.0, lonlat.1) is Some(xy) else {
      fail(name)
    }
    let tol = if crs.is_geographic() { 1.0e-9 } else { 1.0e-6 }
    assert_true(near(xy, expected, tol), msg=name)
    guard @proj.transform(crs, wgs, expected.0, expected.1) is Some(back) else {
      fail(name)
    }
    assert_true(near(back, lonlat, 1.0e-7), msg=name)
  }
}
`;
await writeFile(path.join(ROOT, "proj/projections_test.mbt"), text);
console.log(`${cases.length} cases`);
