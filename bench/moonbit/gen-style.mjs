// Writes the MoonBit API's typed style functions (moonbit/mbtmap/style/{layers,sources}.g.mbt) from
// MapLibre's style specification (v8.json of @maplibre/maplibre-gl-style-spec, the version bench pins).
// Usage: node moonbit/gen-style.mjs [--check] (--check fails when the files differ from what it writes).
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "moonbit/mbtmap/style");

/** Layers that draw a vector or GeoJSON source's features, and so take `source_layer` and `filter`. */
const FEATURE_LAYERS = new Set(["fill", "line", "symbol", "circle", "heatmap", "fill-extrusion"]);

/** Words MoonBit keeps for itself (a warning now): an argument named so gets a trailing `_`. */
const RESERVED = new Set(["volatile", "method", "where", "loop", "fn"]);

const ident = (name) => {
  const id = name.replace(/-/g, "_").replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
  return RESERVED.has(id) ? `${id}_` : id;
};

const HEADER = (what) => `// Generated by bench/moonbit/gen-style.mjs from MapLibre's style specification (${what}); do not edit.\n`;

function layerFunction(spec, kind) {
  const name = ident(kind);
  const paint = Object.keys(spec[`paint_${kind}`] ?? {});
  const layout = Object.keys(spec[`layout_${kind}`] ?? {});
  const feature = FEATURE_LAYERS.has(kind);
  const sourced = kind !== "background";
  const params = ["  id : String,"];
  if (sourced) params.push("  source~ : String,");
  if (feature) params.push("  source_layer? : String,", "  filter? : @expr.Expr,");
  params.push("  minzoom? : Double,", "  maxzoom? : Double,");
  for (const p of [...paint, ...layout]) params.push(`  ${ident(p)}? : @expr.Expr,`);
  const body = ["  let paint = Map([])"];
  for (const p of paint) body.push(`  put_expr(paint, ${JSON.stringify(p)}, ${ident(p)})`);
  body.push("  let layout = Map([])");
  for (const p of layout) body.push(`  put_expr(layout, ${JSON.stringify(p)}, ${ident(p)})`);
  const source = sourced ? "Some(source)" : "None";
  const sourceLayer = feature ? "source_layer" : "None";
  const filter = feature ? "filter" : "None";
  body.push(`  layer(id, ${JSON.stringify(kind)}, ${source}, ${sourceLayer}, ${filter}, minzoom, maxzoom, paint, layout)`);
  return [
    "///|",
    `/// A \`${kind}\` layer (https://maplibre.org/maplibre-style-spec/layers/#${kind}): its paint and layout`,
    `/// properties are the labelled arguments, named as the specification's with \`_\` for \`-\`.`,
    `pub fn ${name}(`,
    ...params,
    ") -> Layer {",
    ...body,
    "}",
  ].join("\n");
}

/** The MoonBit type of a source property and the `put_*` helper that writes it. */
function sourceType(p) {
  switch (p.type) {
    case "string":
    case "enum":
      return ["String", "put_string"];
    case "number":
      return ["Double", "put_number"];
    case "boolean":
      return ["Bool", "put_bool"];
    case "array":
      if (p.value === "string") return ["Array[String]", "put_strings"];
      if (p.value === "number") return ["Array[Double]", "put_numbers"];
      return ["Json", "put_json"];
    default:
      return ["Json", "put_json"];
  }
}

function sourceFunction(spec, kind) {
  const props = Object.entries(spec[`source_${kind.replace(/-/g, "_")}`]).filter(([k]) => k !== "type" && k !== "*");
  const required = props.filter(([, p]) => p.required);
  const optional = props.filter(([, p]) => !p.required);
  const params = [
    ...required.map(([k, p]) => `  ${ident(k)}~ : ${sourceType(p)[0]},`),
    ...optional.map(([k, p]) => `  ${ident(k)}? : ${sourceType(p)[0]},`),
  ];
  const body = [`  let o : Map[String, Json] = { "type": ${JSON.stringify(kind)} }`];
  for (const [k, p] of props) {
    const [, put] = sourceType(p);
    body.push(`  ${put}(o, ${JSON.stringify(k)}, ${p.required ? `Some(${ident(k)})` : ident(k)})`);
  }
  body.push("  { json: Json::object(o) }");
  return [
    "///|",
    `/// A \`${kind}\` source (https://maplibre.org/maplibre-style-spec/sources/#${kind}): its properties are the`,
    "/// labelled arguments, named as the specification's in snake case.",
    `pub fn ${ident(kind)}_source(`,
    ...params,
    ") -> Source {",
    ...body,
    "}",
  ].join("\n");
}

/** The two generated files' contents, by file name. */
export function generate() {
  const spec = require("@maplibre/maplibre-gl-style-spec/src/reference/v8.json");
  const version = require("@maplibre/maplibre-gl-style-spec/package.json").version;
  const what = `@maplibre/maplibre-gl-style-spec ${version}`;
  const layers = Object.keys(spec.layer.type.values).map((k) => layerFunction(spec, k));
  const sources = ["vector", "raster", "raster-dem", "geojson", "image", "video"].map((k) => sourceFunction(spec, k));
  return {
    "layers.g.mbt": HEADER(what) + "\n" + layers.join("\n\n") + "\n",
    "sources.g.mbt": HEADER(what) + "\n" + sources.join("\n\n") + "\n",
  };
}

/** `text` without whitespace and trailing commas, so a file `moon fmt` laid out compares equal. */
export const normalize = (text) => text.replace(/\s+/g, "").replace(/,([)}\]])/g, "$1");

/** The generated files that differ from what `generate` writes (layout aside). */
export async function staleFiles() {
  const stale = [];
  for (const [file, text] of Object.entries(generate())) {
    const now = await readFile(path.join(OUT, file), "utf8").catch(() => "");
    if (normalize(now) !== normalize(text)) stale.push(file);
  }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  const stale = check ? await staleFiles() : [];
  if (!check) for (const [file, text] of Object.entries(generate())) await writeFile(path.join(OUT, file), text);
  if (stale.length > 0) {
    console.error(`stale: ${stale.join(", ")} (run node moonbit/gen-style.mjs, then moon fmt)`);
    process.exit(1);
  }
}
